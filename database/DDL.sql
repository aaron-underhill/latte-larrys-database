-- This file serves as the basis for our database. It creates the tables used by our fictional coffee shop,
-- Unreal Coffee, including: passwords, employees, customers, orders, drinks, and orders_drinks.
--
-- This project was originally developed for a database course and later revisited and improved as part of
-- my continued software-development work. Improvements include cleaner CRUD behavior, stronger handling of
-- relational integrity, automatic Order total calculations, improved orders_drinks functionality, and a
-- redesigned user interface.
--
-- This version of the database uses PostgreSQL. Example data is included at the end of the file to provide
-- a predictable baseline for testing.


BEGIN;


-- Drop tables in reverse dependency order so existing
-- foreign-key relationships do not prevent recreation.
DROP TABLE IF EXISTS orders_drinks;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS employees;
DROP TABLE IF EXISTS customers;
DROP TABLE IF EXISTS drinks;
DROP TABLE IF EXISTS passwords;


-- SQL statement to create our passwords table.
CREATE TABLE passwords (
    id_password INTEGER GENERATED BY DEFAULT AS IDENTITY,
    password VARCHAR(256) NOT NULL,

    PRIMARY KEY (id_password)
);


-- SQL statement to create our employees table.
CREATE TABLE employees (
    id_employee INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_password INTEGER NOT NULL,
    name VARCHAR(145) NOT NULL,
    phone_num VARCHAR(20) NOT NULL,
    email VARCHAR(145) NOT NULL,
    address VARCHAR(145) NOT NULL,

    PRIMARY KEY (id_employee),

    FOREIGN KEY (id_password)
        REFERENCES passwords(id_password)
        ON DELETE CASCADE
);


-- SQL statement to create our customers table.
CREATE TABLE customers (
    id_customer INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(145) NOT NULL,
    phone_num VARCHAR(20) NULL,
    email VARCHAR(145) NULL,

    PRIMARY KEY (id_customer)
);


-- SQL statement to create our orders table.
CREATE TABLE orders (
    id_order INTEGER GENERATED BY DEFAULT AS IDENTITY,

    id_employee INTEGER NULL,

    -- id_customer allows NULL because deleting a Customer
    -- should NOT delete the Order. PostgreSQL instead sets
    -- the Order's id_customer value to NULL.
    id_customer INTEGER NULL,

    -- total_price is calculated from the Drinks belonging to the Order.
    -- A newly-created Order begins at $0.00 because it has no Drinks yet.
    total_price DECIMAL(7,2) NOT NULL DEFAULT 0.00,

    minutes_to_process DECIMAL(4,1) NOT NULL,
    order_date DATE NOT NULL,

    PRIMARY KEY (id_order),

    -- If an Employee is deleted, keep the Order
    -- and remove only the Employee reference.
    FOREIGN KEY (id_employee)
        REFERENCES employees(id_employee)
        ON DELETE SET NULL,

    -- If a Customer is deleted, keep the Order
    -- and remove only the Customer reference.
    FOREIGN KEY (id_customer)
        REFERENCES customers(id_customer)
        ON DELETE SET NULL
);


-- SQL statement to create our drinks table.
CREATE TABLE drinks (
    id_drink INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(145) NOT NULL,
    description VARCHAR(145) NOT NULL,
    price DECIMAL(5,2) NOT NULL,

    PRIMARY KEY (id_drink)
);


-- SQL statement to create our orders_drinks table.
-- This junction table connects Drinks to Orders and stores quantity and line totals.
CREATE TABLE orders_drinks (
    id_order_drink INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_order INTEGER NOT NULL,
    id_drink INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    drink_total DECIMAL(7,2) NOT NULL,

    PRIMARY KEY (id_order_drink),

    FOREIGN KEY (id_order)
        REFERENCES orders(id_order)
        ON DELETE CASCADE,

    FOREIGN KEY (id_drink)
        REFERENCES drinks(id_drink)
);


